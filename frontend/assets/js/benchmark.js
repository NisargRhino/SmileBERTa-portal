/* Benchmark page — renders evaluation/results into the published tables.
   The data file is generated by evaluation/report.py, so the page cannot drift
   from the runs that produced the numbers. */
(function () {
  const { $, esc, fmt } = SB;

  const CLASS_LABELS = {
    antiinfective: 'Anti-infective', antineoplastic: 'Antineoplastic', cns: 'CNS',
    cardio: 'Cardiovascular', antiinflammatory: 'Anti-inflammatory',
    gastrointestinal: 'Gastrointestinal', hematologic: 'Hematologic',
    respiratorysystem: 'Respiratory', dermatologic: 'Dermatologic',
    reproductivecontrol: 'Reproductive', lipidregulating: 'Lipid-regulating',
    urological: 'Urological',
  };
  const MODEL_LABELS = {
    majority_class: 'Majority class', random_forest_ecfp4: 'Random forest (ECFP4)',
    logistic_regression_ecfp4: 'Logistic regression (ECFP4)',
    nearest_neighbour_tanimoto: 'Nearest neighbour (Tanimoto)',
    most_common_fragment: 'Most common fragment',
  };

  const nm = (k) => CLASS_LABELS[k] || MODEL_LABELS[k] || k;

  function table(headers, rows, cls = 'table bm') {
    return `<div class="table-wrap"><table class="${cls}"><thead><tr>${headers
      .map((h) => `<th class="${h.num ? 'num' : ''}">${esc(h.label ?? h)}</th>`).join('')}</tr></thead>
      <tbody>${rows.map((r) => `<tr>${r.map((c, i) => `<td class="${headers[i].num ? 'num' : ''}">${c}</td>`).join('')}</tr>`).join('')}</tbody></table></div>`;
  }

  function stat(value, key, sub, tone = '') {
    return `<div class="bm-stat ${tone}"><div class="v">${value}</div><div class="k">${esc(key)}</div>${
      sub ? `<div class="s">${sub}</div>` : ''}</div>`;
  }

  function renderHero(d) {
    const base = d.baselines && d.baselines.scaffold.classification.random_forest_ecfp4;
    const rand = d.baselines && d.baselines.random.classification.random_forest_ecfp4;
    const shippedC = d.shipped && d.shipped.scaffold.classification;
    const shippedF = d.shipped && d.shipped.scaffold.fragment;
    const out = [];
    if (base && rand) {
      out.push(stat(`${fmt(rand.macro_f1, 2)} → ${fmt(base.macro_f1, 2)}`, 'Random → scaffold split',
        'Macro-F1 of the same random forest. The drop is what honest splitting costs — and what a random split was hiding.'));
    }
    if (shippedC) {
      out.push(stat(fmt(shippedC.macro_f1, 2), 'Shipped classifier, macro-F1',
        'Measured on the scaffold test set, but this model was trained before the split existed, so it has very likely seen these molecules. Treat it as an upper bound, not a result.'));
    }
    if (shippedF) {
      out.push(stat(`${(shippedF.substructure_rate * 100).toFixed(0)}%`,
        'Fragments that are real substructures',
        'Of the fragments the tool returns, the share genuinely contained in the molecule they came from. The rest are hallucinations.', 'bad'));
      out.push(stat(`${(shippedF.validity_rate_raw * 100).toFixed(0)}%`, 'Raw outputs that parse',
        'How often the fragment model emits a valid SMILES before any repair. The remainder go through the nearest-fragment fallback.', 'bad'));
    }
    $('#hero').innerHTML = out.join('');
  }

  function renderSplit(d) {
    const reps = d.splits && d.splits.reports;
    if (!reps) return;
    const rows = Object.entries(reps).map(([name, r]) => [
      esc(name.replace('_', ' · ')), r.sizes.train, r.sizes.validation, r.sizes.test,
      r.shared_scaffolds_train_test === 0
        ? '<span class="badge green">0</span>'
        : `<span class="badge red">${r.shared_scaffolds_train_test}</span>`,
    ]);
    $('#split-table').innerHTML = table(
      ['Dataset · split', { label: 'Train', num: 1 }, { label: 'Validation', num: 1 },
        { label: 'Test', num: 1 }, { label: 'Scaffolds in both train and test', num: 1 }], rows);
  }

  function renderGap(d) {
    if (!d.baselines) return;
    const pairs = [
      ['Random forest', d.baselines.random.classification.random_forest_ecfp4.macro_f1,
        d.baselines.scaffold.classification.random_forest_ecfp4.macro_f1],
      ['Logistic regression', d.baselines.random.classification.logistic_regression_ecfp4.macro_f1,
        d.baselines.scaffold.classification.logistic_regression_ecfp4.macro_f1],
    ];
    if (d.shipped) {
      pairs.push(['Shipped transformer', d.shipped.random.classification.macro_f1,
        d.shipped.scaffold.classification.macro_f1]);
    }
    if (d.headline_classification && d.headline_classification.gap) {
      const g = d.headline_classification.gap;
      pairs.push(['Retrained transformer', g.random, g.scaffold]);
    }
    const bars = pairs.map(([label, r, s]) => `
      <div class="gap-bar"><span class="lbl">${esc(label)}</span>
        <span class="track"><span class="fill" style="width:${(r * 100).toFixed(0)}%;background:rgba(148,163,184,.55)"></span></span>
        <span class="num">${fmt(r, 3)}</span></div>
      <div class="gap-bar"><span class="lbl" style="opacity:.6">— scaffold</span>
        <span class="track"><span class="fill" style="width:${(s * 100).toFixed(0)}%;background:var(--grad)"></span></span>
        <span class="num">${fmt(s, 3)}</span></div>
      <div style="font-size:.76rem;color:var(--muted);margin:2px 0 14px 128px">gap ${fmt(r - s, 3)}${
        Math.abs(r - s) < 0.05 ? ' — a model with no gap has most likely seen the test molecules' : ''}</div>`);
    $('#gap-chart').innerHTML =
      `<div class="label">Macro-F1: random split vs scaffold split</div>${bars.join('')}`;
  }

  function renderClassification(d) {
    const rows = [];
    const add = (label, m, note) => {
      if (!m) return;
      rows.push([esc(label) + (note ? ` <span class="muted" style="font-size:.74rem">${esc(note)}</span>` : ''),
        fmt(m.macro_f1, 3), fmt(m.micro_f1, 3), fmt(m.top_3_accuracy, 3),
        fmt(m.subset_accuracy, 3), fmt(m.hamming_loss, 3)]);
    };
    if (d.baselines) {
      Object.entries(d.baselines.scaffold.classification).forEach(([k, v]) => {
        if (!k.startsWith('_')) add(nm(k), v);
      });
    }
    if (d.headline_classification) {
      add('Transformer, retrained on this split', d.headline_classification.scaffold.full_test_metrics);
    }
    if (d.shipped) add('Shipped transformer', d.shipped.scaffold.classification, '(contaminated)');
    $('#cls-summary').innerHTML = table(
      ['Model', { label: 'Macro-F1', num: 1 }, { label: 'Micro-F1', num: 1 },
        { label: 'Top-3', num: 1 }, { label: 'Exact set', num: 1 }, { label: 'Hamming', num: 1 }], rows)
      + `<p style="font-size:.8rem;color:var(--muted);margin-top:8px">Scaffold-split test set.
         "Exact set" is the fraction where the predicted set of categories matched the true set exactly.
         The shipped model's row is marked contaminated because it was trained before this split existed.</p>`;

    const perClassSources = [];
    if (d.baselines) perClassSources.push(['Random forest', d.baselines.scaffold.classification.random_forest_ecfp4.per_class]);
    if (d.headline_classification) perClassSources.push(['Retrained transformer', d.headline_classification.scaffold.full_test_metrics.per_class]);
    if (d.shipped) perClassSources.push(['Shipped (contaminated)', d.shipped.scaffold.classification.per_class]);
    if (!perClassSources.length) return;

    const cats = Object.keys(perClassSources[0][1]);
    const headers = ['Class', { label: 'Support', num: 1 }];
    perClassSources.forEach(([name]) => headers.push({ label: `${name} F1`, num: 1 }));
    const prows = cats.map((c) => {
      const row = [esc(nm(c)), perClassSources[0][1][c].support];
      perClassSources.forEach(([, pc]) => {
        const f1 = pc[c] ? pc[c].f1 : null;
        const colour = f1 === null ? '' : f1 >= 0.7 ? 'color:#6ee7b7' : f1 >= 0.4 ? 'color:#fcd34d' : 'color:#fca5a5';
        row.push(`<span style="${colour}">${f1 === null ? '—' : fmt(f1, 3)}</span>`);
      });
      return row;
    });
    $('#cls-perclass').innerHTML = table(headers, prows);
  }

  function renderFragment(d) {
    const rows = [];
    const add = (label, m, note) => {
      if (!m) return;
      rows.push([esc(label) + (note ? ` <span class="muted" style="font-size:.74rem">${esc(note)}</span>` : ''),
        fmt(m.validity_rate_raw, 3), fmt(m.exact_match_rate, 3),
        fmt(m.mean_tanimoto_to_reference, 3), fmt(m.substructure_rate, 3),
        fmt(m.rule_of_three_pass_rate, 3)]);
    };
    if (d.baselines) {
      Object.entries(d.baselines.scaffold.fragment).forEach(([k, v]) => {
        if (!k.startsWith('_')) add(nm(k), v);
      });
    }
    if (d.headline_fragment) add('Transformer, retrained on this split', d.headline_fragment.scaffold.full_test_metrics);
    if (d.shipped) add('Shipped transformer', d.shipped.scaffold.fragment, '(contaminated)');
    if (d.memorisation_control_fragment) {
      add('Same recipe, trained on the test set', d.memorisation_control_fragment.full_test_metrics, '(control)');
    }
    $('#frag-summary').innerHTML = table(
      ['Model', { label: 'Valid SMILES', num: 1 }, { label: 'Exact match', num: 1 },
        { label: 'Tanimoto', num: 1 }, { label: 'Is a substructure', num: 1 },
        { label: 'Rule of 3', num: 1 }], rows)
      + `<p style="font-size:.8rem;color:var(--muted);margin-top:8px">
        Scaffold-split test set of 22 molecules — small, so read these as direction rather than precision.
        <b>Is a substructure</b> is the fraction of returned fragments genuinely contained in the input molecule;
        anything else is a fragment of some other molecule. The control row was trained with the test set in its
        training data on purpose, to show what the recipe can do when it is allowed to memorise.</p>`;
  }

  function renderCases(d) {
    const cases = d.named_examples && d.named_examples.cases;
    if (!cases) return;
    $('#cases').innerHTML = cases.map((c) => {
      const verdict = c.correct === null ? '<span class="badge">not in dataset</span>'
        : c.correct ? '<span class="badge green">matches a true label</span>'
          : '<span class="badge red">wrong</span>';
      return `<div class="case">
        <h4>${esc(c.name)} ${verdict}</h4>
        <div class="why">${esc(c.why)}</div>
        <div class="io">
          ${c.true_labels ? `<div>dataset label &nbsp;<b>${esc(c.true_labels.join(', '))}</b></div>` : ''}
          <div>raw output &nbsp;<b>${esc(c.raw_output)}</b>${
            c.raw_was_a_valid_label ? '' : ' <span class="muted">— not a label; edit distance picked the nearest one</span>'}</div>
          <div>prediction &nbsp;<b>${esc(c.predicted.join(', ') || '—')}</b></div>
          <div>fragment model &nbsp;<b>${esc(c.fragment.raw_output)}</b>
            <span class="muted">${c.fragment.valid_smiles ? 'valid SMILES' : 'does not parse'},
            ${c.fragment.is_substructure_of_input ? 'is part of the molecule' : 'not part of the molecule'}</span></div>
        </div></div>`;
    }).join('');
  }

  function renderProvenance(d) {
    const rows = [
      ['Generated', esc(d.generated || '—')],
      ['Repository commit', `<code>${esc(d.commit || '—')}</code>`],
    ];
    if (d.datasets) {
      Object.entries(d.datasets).forEach(([k, v]) => {
        rows.push([`${esc(k)} dataset`, `<code>${esc(v.file)}</code> · sha256 <code>${esc(v.sha256_16)}</code>`]);
      });
    }
    if (d.splits && d.splits.files) {
      Object.entries(d.splits.files).forEach(([k, v]) => {
        rows.push([`split · ${esc(k)}`, `<code>${esc(v.path)}</code> · sha256 <code>${esc(v.sha256_16)}</code>`]);
      });
    }
    $('#provenance').innerHTML = table(['Item', 'Value'], rows)
      + `<p style="font-size:.84rem;color:var(--text-2);margin-top:12px;line-height:1.6">
        Every number here is produced by the scripts in <code>evaluation/</code> and written to
        <code>evaluation/results/</code>. The splits are committed files, not regenerated at run time,
        so these results stay comparable with later ones. Full write-up:
        <a href="https://github.com/NisargRhino/SmileBERTa-portal/blob/main/BENCHMARK.md">BENCHMARK.md</a>.</p>`;
  }

  async function init() {
    try {
      const res = await fetch('assets/data/benchmark.json', { cache: 'no-cache' });
      if (!res.ok) throw new Error('Benchmark data is not available yet.');
      const d = await res.json();
      renderHero(d); renderSplit(d); renderGap(d);
      renderClassification(d); renderFragment(d); renderCases(d); renderProvenance(d);
      $('#loading').classList.add('hidden');
      $('#content').classList.remove('hidden');
    } catch (e) {
      $('#loading').innerHTML = `<span style="color:var(--red)">${esc(e.message)}</span>`;
    }
  }
  init();
})();
