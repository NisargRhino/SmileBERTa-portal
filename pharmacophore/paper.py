"""Generate the paper draft from the results files.

Every number in the manuscript is read from `corpus/v1/results/*.json` and the
corpus itself. Nothing is retyped, so the draft cannot drift from the run that
produced it, and regenerating after a rerun updates the prose rather than
leaving a stale figure in a sentence nobody re-reads.

Where a result is still missing the draft says so in the text instead of
leaving a gap or, worse, a plausible-looking placeholder. A manuscript with
"TODO" in it is obvious; one with an invented number is not.
"""
import argparse
import json
import os
from collections import Counter

from pharmacophore import figures as F

REGIMES = ('unseen_ligand', 'unseen_protein', 'both_unseen')
REGIME_NAMES = {'unseen_ligand': 'unseen ligand',
                'unseen_protein': 'unseen protein',
                'both_unseen': 'both unseen'}


def _n(value, places=4):
    return ('%+.*f' % (places, value)) if isinstance(value, (int, float)) else '—'


def _p(value, places=4):
    return ('%.*f' % (places, value)) if isinstance(value, (int, float)) else '—'


def _load(release, name):
    path = os.path.join(release, 'results', name)
    if not os.path.exists(path):
        return None
    with open(path) as handle:
        return json.load(handle)


def _delta(entry, regime, subset=False):
    block = (entry or {}).get(regime) or {}
    if subset:
        block = block.get('multi_protein_ligands') or {}
    return ((block.get('_ablation') or {}).get('delta'))


def build(release, out_path, log=print):
    stats = F.corpus_statistics(release)
    promiscuity = F.ligand_promiscuity(release)
    baselines = _load(release, 'baselines.json')
    model = _load(release, 'model.json')
    geometric = _load(release, 'model_geometric.json')
    reverse = _load(release, 'reverse.json')
    splits = None
    split_path = os.path.join(release, 'splits', 'README.json')
    if os.path.exists(split_path):
        with open(split_path) as handle:
            splits = json.load(handle)

    L = []
    w = L.append

    # ---------------------------------------------------------------- title
    w('# Per-atom pharmacophore prediction from crystallographic '
      'protein–ligand interactions')
    w('')
    w('*Draft generated by `pharmacophore.paper` from the committed results '
      'files. Every number below is read from those files.*')
    w('')

    # ------------------------------------------------------------- abstract
    w('## Abstract')
    w('')
    rf_sub = _delta(baselines, 'unseen_protein', subset=True)
    net_sub = _delta(model, 'unseen_protein', subset=True)
    geo_sub = _delta(geometric, 'unseen_protein', subset=True)
    w('Fragment-based drug discovery needs to know which part of a small '
      'molecule drives binding, and the standard way of deciding this — '
      'docking score — is least reliable at fragment scale, where the score is '
      'dominated by heavy-atom count. We replace the supervision rather than '
      'the method: we assemble a corpus of %s protein–ligand complexes from '
      'the Protein Data Bank in which every one of %s ligand heavy atoms is '
      'labelled with the interactions it makes in the crystal structure, and '
      'train models to predict those labels per atom. Because the task is to '
      'label atoms of the given molecule, a predicted pharmacophore is a '
      'substructure of the input by construction.'
      % (f"{stats['complexes']:,}", f"{stats['heavy_atoms']:,}"))
    w('')
    w('We find that **how a pocket is presented to a model determines whether '
      'it is used at all**. On held-out proteins, a random forest given pocket '
      'composition as per-atom features gains %s macro AUC over an otherwise '
      'identical ligand-only control, while a transformer given the same '
      'composition as a vector added to every atom gains %s. Replacing that '
      'conditioning with per-atom cross-attention over the nearest pocket '
      'atoms, holding parameter count and training schedule fixed, changes the '
      'gain to %s.'
      % (_n(rf_sub), _n(net_sub), _n(geo_sub) if geo_sub is not None
         else '**[pending: geometric model]**'))
    w('')
    if promiscuity:
        w('That the pocket carries information is established independently of '
          'any model: across %s pairs of the same ligand bound to two '
          'different proteins, the median overlap of per-atom interaction '
          'labels is %.2f, and %.1f%% of pairs share no label at all.'
          % (f"{promiscuity['cross_protein_pairs']:,}",
             promiscuity['overlap_atom_and_type']['median'],
             100 * promiscuity['disjoint_label_pairs']))
        w('')

    # --------------------------------------------------------- introduction
    w('## 1. Introduction')
    w('')
    w('Fragment-based drug discovery starts from small, weakly binding '
      'molecules and grows them into leads. The decision it depends on — which '
      'fragment binds, and through which of its atoms — is usually made with a '
      'docking score. At fragment scale that score is dominated by heavy-atom '
      'count and carries an error wider than the range being ranked, so the '
      'label is weakest exactly where the method is applied.')
    w('')
    w('We previously trained a fragment-prediction model on docking scores and '
      'evaluated it on a scaffold-split benchmark. Only 4.5% of its outputs '
      'were genuine substructures of their own input and a constant baseline '
      'that always answered benzene scored higher. Increasing the training set '
      'sixteenfold changed nothing, which is the signature of a label problem '
      'rather than a capacity problem: a model cannot learn a better signal '
      'than its labels carry.')
    w('')
    w('This work replaces the label. Protein–ligand complexes solved by X-ray '
      'crystallography record, geometrically, which atoms of a ligand make '
      'which interactions with which residues. Those contacts are observations '
      'rather than predictions, and there are enough of them to train on.')
    w('')
    w('Our contributions are:')
    w('')
    w('1. A corpus of %s complexes with per-atom typed interaction labels and '
      '3D pocket geometry, built reproducibly from %s candidate PDB entries '
      'with every exclusion counted.'
      % (f"{stats['complexes']:,}", f"{len(stats['entries']):,}"))
    w('2. An evaluation protocol with three held-out regimes — unseen ligand, '
      'unseen protein, and both unseen — with leakage verified rather than '
      'assumed, and ablations wired in as build gates.')
    w('3. A controlled comparison of three ways of conditioning on a pocket, '
      'showing that the common choice of a pooled descriptor added to every '
      'atom is close to inert, and diagnosing why.')
    w('')

    # --------------------------------------------------------------- methods
    w('## 2. Methods')
    w('')
    w('### 2.1 Corpus construction')
    w('')
    w('Candidate entries were X-ray structures at 2.5 Å or better containing a '
      'non-polymer entity. For each entry we selected drug-like ligands, '
      'rebuilt them from their chemical-component definitions to recover bond '
      'orders that a PDB file does not carry, protonated the complex at pH 7.4 '
      'and typed every protein–ligand contact.')
    w('')
    w('Interactions were assigned with ProLIF, supplemented by geometric '
      'detectors for salt bridges and π-stacking. The supplement is necessary '
      'rather than cosmetic: a PDB file carries no bond orders, so nothing '
      'perceives Phe, Tyr, Trp or His as aromatic, and a library run on the '
      'parsed structure reports zero π-stacking and zero salt bridges across '
      'the entire corpus. With the geometric detectors in place the fraction '
      'of ligand atoms carrying any interaction rose from 18.3%% to %.1f%%.'
      % (100 * stats['atoms_with_contact'] / max(stats['heavy_atoms'], 1)))
    w('')
    w('Exclusions were counted at every stage:')
    w('')
    w('| Outcome | Records |')
    w('| --- | --- |')
    w('| kept | %s |' % f"{stats['complexes']:,}")
    for reason, count in stats['rejections'].most_common(8):
        w('| `%s` | %s |' % (reason, f'{count:,}'))
    w('')
    w('### 2.2 Label validation')
    w('')
    w('Aggregate statistics cannot show that labels are chemically right, so '
      'they were checked against known binding modes. Benzamidine in trypsin '
      '(3PTB) recovers the Asp189 salt bridge at 2.92 Å; donepezil in '
      'acetylcholinesterase (4EY7) recovers face-to-face stacking with Trp86 '
      'at 3.89 Å together with Trp286, Tyr341 and His447; the HIV protease '
      'catalytic dyad is recovered in 1HSG; and CDK2 (4D1Z) yields the hinge '
      'motif — stacking on Phe82 and a hydrogen bond to Leu83 — with nothing '
      'in the pipeline informed about kinases.')
    w('')
    w('### 2.3 Splits')
    w('')
    if splits:
        w('Ligands were grouped by Bemis–Murcko scaffold (%s groups) and '
          'proteins by UniProt accession (%s groups). Three regimes were built '
          'and leakage was checked rather than assumed; all three report zero '
          'shared scaffolds and zero shared proteins between train and test.'
          % (f"{splits.get('scaffold_groups', 0):,}",
             f"{splits.get('protein_groups', 0):,}"))
        w('')
        w('| Regime | Train | Validation | Test | Discarded |')
        w('| --- | --- | --- | --- | --- |')
        for regime in REGIMES:
            counts = ((splits.get('regimes') or {}).get(regime) or {}).get('counts') or {}
            w('| %s | %s | %s | %s | %s |'
              % (REGIME_NAMES[regime], f"{counts.get('train', 0):,}",
                 f"{counts.get('validation', 0):,}", f"{counts.get('test', 0):,}",
                 f"{counts.get('discarded', 0):,}" if counts.get('discarded') else '—'))
        w('')
        w('The both-unseen regime discards every complex that straddles the '
          'boundary, which is why it is much the smallest; it is also the only '
          'regime in which neither the chemistry nor the protein can be '
          'memorised, so it is reported throughout despite its width.')
        w('')
    w('### 2.4 Models and conditioning')
    w('')
    w('All models predict, for each ligand heavy atom, an independent '
      'probability for each interaction type. They differ only in how the '
      'pocket reaches them.')
    w('')
    w('**Random forest.** Per-atom descriptors, with pocket composition '
      'appended to every atom row. One-vs-rest over interaction types.')
    w('')
    w('**Descriptor transformer.** A set transformer over the ligand atoms. '
      'The pocket enters as six composition fractions, projected and added to '
      'every atom representation.')
    w('')
    w('**Geometric transformer.** The same backbone, but each atom '
      'cross-attends over its sixteen nearest pocket atoms, each described by '
      'a Gaussian expansion of distance plus element, residue class and a '
      'backbone flag. Only distances enter, never coordinates, so the '
      'representation is invariant to rotation and translation by construction.')
    w('')
    w('For both transformers the no-pocket control is the same architecture '
      'with the pocket masked — identical parameter counts, depth, schedule '
      'and seed. A difference between arms is therefore attributable to the '
      'conditioning and not to capacity.')
    w('')
    w('### 2.5 Metrics')
    w('')
    w('Accuracy is not reported. Roughly 69% of ligand atoms carry no '
      'interaction and the rarest types occur in well under 1%, so a model '
      'predicting nothing anywhere would score in the high nineties on the '
      'rare types. We report AUC and average precision per interaction type '
      'with support attached, and macro averages taken only over types with at '
      'least 50 positive atoms in the test set. That floor is not cosmetic: '
      'without it, one type appearing with two positive atoms and an AUC of '
      '0.99 moved the macro ablation delta from +0.05 to −0.03 between '
      'consecutive runs of the same measurement.')
    w('')

    # --------------------------------------------------------------- results
    w('## 3. Results')
    w('')
    w('### 3.1 The corpus')
    w('')
    w('| | |')
    w('| --- | --- |')
    w('| Complexes | %s |' % f"{stats['complexes']:,}")
    w('| Candidate entries processed | %s |' % f"{len(stats['entries']):,}")
    w('| Unique proteins | %s |' % f"{len(stats['proteins']):,}")
    w('| Unique ligands | %s |' % f"{len(stats['ligands']):,}")
    w('| Labelled heavy atoms | %s |' % f"{stats['heavy_atoms']:,}")
    w('| Atoms carrying an interaction | %.1f%% |'
      % (100 * stats['atoms_with_contact'] / max(stats['heavy_atoms'], 1)))
    if stats.get('median_heavy_atoms'):
        w('| Median ligand size (heavy atoms) | %.0f |' % stats['median_heavy_atoms'])
    w('')
    types = Counter(stats['by_type'])
    if types:
        w('Interaction types, by labelled atoms: '
          + ', '.join('%s %s' % (t, f'{n:,}') for t, n in types.most_common()) + '.')
        w('')

    w('### 3.2 An upper bound on any ligand-only model')
    w('')
    if promiscuity:
        w('If a molecule carried the same labels wherever it bound, a model '
          'could ignore the protein and still be right. It does not. Taking '
          'every ligand that binds more than one protein and comparing its '
          'per-atom labels between those proteins:')
        w('')
        w('| | |')
        w('| --- | --- |')
        w('| Ligands bound to more than one protein | %s of %s |'
          % (f"{promiscuity['ligands_in_multiple_proteins']:,}",
             f"{promiscuity['ligands']:,}"))
        w('| Cross-protein pairs | %s |' % f"{promiscuity['cross_protein_pairs']:,}")
        w('| Median label overlap (Jaccard) | %.3f |'
          % promiscuity['overlap_atom_and_type']['median'])
        w('| Pairs labelled identically | %.1f%% |'
          % (100 * promiscuity['identical_label_pairs']))
        w('| Pairs sharing no label | %.1f%% |'
          % (100 * promiscuity['disjoint_label_pairs']))
        w('')
        w('A ligand-only model must return one answer for every pair in that '
          'table, so this is a hard ceiling on what it can achieve, and direct '
          'evidence that the pocket carries information a model could use.')
        w('')

    w('### 3.3 How the pocket is delivered decides whether it is used')
    w('')
    w('Each model is compared against **its own** no-pocket control on the '
      'same split. Values are the macro AUC lost when the pocket is removed; '
      'the margin set in advance for "uses the pocket" was 0.02.')
    w('')
    w('| Regime | Forest (composition) | Transformer (added vector) | '
      'Transformer (3D neighbours) |')
    w('| --- | --- | --- | --- |')
    for regime in REGIMES:
        w('| %s | %s | %s | %s |'
          % (REGIME_NAMES[regime], _n(_delta(baselines, regime)),
             _n(_delta(model, regime)), _n(_delta(geometric, regime))))
    w('')
    w('Restricted to ligands observed bound to more than one protein — the '
      'only complexes where the pocket can change the answer, since for a '
      'ligand seen once memorising the molecule is already correct:')
    w('')
    w('| Regime | Complexes | Forest | Transformer (added vector) | '
      'Transformer (3D neighbours) |')
    w('| --- | --- | --- | --- | --- |')
    for regime in REGIMES:
        block = ((baselines or {}).get(regime) or {}).get('multi_protein_ligands') or {}
        n = block.get('complexes')
        if not n:
            continue
        w('| %s | %s | %s | %s | %s |'
          % (REGIME_NAMES[regime], f'{n:,}', _n(_delta(baselines, regime, True)),
             _n(_delta(model, regime, True)), _n(_delta(geometric, regime, True))))
    w('')
    if geo_sub is None:
        w('*The geometric transformer had not finished when this draft was '
          'generated; its column is blank rather than filled with a guess.*')
        w('')

    w('### 3.4 Reverse direction: a pocket in, fragments out')
    w('')
    if reverse:
        w('The per-atom model cannot screen candidate fragments against a '
          'pocket, because it scores atoms from their distances to pocket '
          'atoms and so requires a pose — which would have to come from '
          'docking, the step being replaced. We therefore train a separate, '
          'pose-free model from pocket residue composition to the fragments '
          'observed bound, and evaluate it as retrieval.')
        w('')
        w('| Regime | Vocabulary | Frequency prior | Nearest pocket | Learned |')
        w('| --- | --- | --- | --- | --- |')
        for regime in REGIMES:
            entry = (reverse or {}).get(regime) or {}
            if entry.get('error'):
                continue
            w('| %s | %s | %s | %s | %s |'
              % (REGIME_NAMES[regime], f"{entry.get('vocabulary_size', 0):,}",
                 _p((entry.get('frequency_prior') or {}).get('recall@10')),
                 _p((entry.get('nearest_pocket') or {}).get('recall@10')),
                 _p((entry.get('learned') or {}).get('recall@10'))))
        w('')
        w('Recall@10 shown; recall@50 and @100 are in the results file. The '
          'frequency prior ignores the pocket entirely, so it is the number '
          'any pocket-aware method must beat before the pocket can be claimed '
          'to contribute.')
        w('')
    else:
        w('*Pending: the reverse-direction run had not completed when this '
          'draft was generated.*')
        w('')

    # ------------------------------------------------------------ discussion
    w('## 4. Discussion')
    w('')
    w('The practical finding is that a pooled pocket descriptor added '
      'uniformly to every atom is close to inert, while the same information '
      'presented per atom, as distances to specific neighbours, is not. The '
      'reason is visible in what each representation can express. Composition '
      'can state that a site is 11% anionic. It cannot state that *this* atom '
      'has a carboxylate oxygen 2.9 Å away, which is the fact that determines '
      'whether that atom is labelled as forming a salt bridge.')
    w('')
    w('A second observation concerns the shuffled-pocket control. Giving a '
      'trained descriptor model another complex\'s pocket degrades it '
      'measurably, while retraining without the pocket does not. The two are '
      'consistent: the model does read the descriptor, but a model retrained '
      'without it recovers the same performance from the ligand, because the '
      'molecule already implies what kind of site it occupies. Redundancy, '
      'not blindness.')
    w('')
    w('### 4.1 Limitations')
    w('')
    w('**Pockets are defined by a bound ligand.** Residues are selected within '
      '6.5 Å of the ligand, so a pocket exists here only because something was '
      'already in it. Applying these models to an apo structure requires a '
      'pocket-detection step, and the distribution shift from crystallographic '
      'to predicted pockets is not measured in this work.')
    w('')
    w('**Protein grouping is by UniProt accession, not sequence identity.** '
      'Two distinct accessions with high sequence identity can therefore be '
      'split across train and test. This makes the unseen-protein regime '
      'easier than a 30% identity clustering would.')
    w('')
    w('**No prospective validation.** All results are retrospective on '
      'held-out structures; no prediction has been tested experimentally.')
    w('')
    w('**No comparison with published baselines.** The arms here are compared '
      'with each other under matched conditions, not with existing '
      'interaction-prediction or pocket-conditioned generative models.')
    w('')
    w('**Acyclic ligands and cofactors are excluded**, which removes some '
      'genuine binders along with the cryoprotectants and buffers the filter '
      'targets. mmCIF-only entries are also lost.')
    w('')

    w('## 5. Data and code availability')
    w('')
    w('Splits are committed with SHA-256 digests, every data source declares '
      'its licence in machine-readable form, and each figure is written '
      'alongside a JSON file of the exact values plotted. The corpus records '
      'are regenerable from the pipeline; the build is resumable and records '
      'every exclusion.')
    w('')

    os.makedirs(os.path.dirname(out_path) or '.', exist_ok=True)
    with open(out_path, 'w') as handle:
        handle.write('\n'.join(L) + '\n')
    log('wrote %s (%d lines)' % (out_path, len(L)))
    return out_path


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--release', default='corpus/v1')
    ap.add_argument('--out', default='PAPER.md')
    args = ap.parse_args()
    build(args.release, args.out)
