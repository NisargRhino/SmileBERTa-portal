#!/usr/bin/env bash
# Re-run the analysis pipeline as the corpus grows, without touching the build.
#
# The build is the long pole and runs under its own watchdog. This loop only
# reads what the build has produced: rebuild the splits, rerun the baselines and
# the model, regenerate the figures, commit the results, sleep, repeat. Each
# cycle leaves a complete and self-consistent set of numbers on disk, so the run
# can be interrupted at any point and whatever finished last is still valid.
#
# Every stage is wrapped in a hard timeout. A stage that overruns is killed and
# the cycle moves on rather than wedging the loop -- the previous cycle's
# results stay in place, which is the whole reason results are written per
# cycle instead of at the end.
set -u
cd "$(dirname "$0")/.."

RELEASE="${RELEASE:-corpus/v1}"
PY="${PY:-/private/tmp/claude-501/-Users-nisargshah-Documents-cs-SmileBERTa-portal/d5665c0f-0ea0-405a-b676-e25fb81ddc4d/scratchpad/tenv/bin/python}"
EPOCHS="${EPOCHS:-30}"
CYCLE_SLEEP="${CYCLE_SLEEP:-3600}"
SPLIT_TIMEOUT="${SPLIT_TIMEOUT:-1800}"
BASELINE_TIMEOUT="${BASELINE_TIMEOUT:-5400}"
TRAIN_TIMEOUT="${TRAIN_TIMEOUT:-9000}"
FIGURE_TIMEOUT="${FIGURE_TIMEOUT:-1800}"

# macOS has no coreutils `timeout`. Run the command, watch it from a second
# process and kill it if it overruns.
run_with_timeout() {
  local limit="$1"; shift
  "$@" &
  local pid=$!
  ( sleep "$limit"; kill -9 "$pid" 2>/dev/null ) &
  local killer=$!
  wait "$pid" 2>/dev/null
  local status=$?
  kill "$killer" 2>/dev/null
  return $status
}

stage() {
  local label="$1" limit="$2"; shift 2
  echo "--- [$(date '+%H:%M:%S')] $label"
  if run_with_timeout "$limit" "$@"; then
    echo "--- [$(date '+%H:%M:%S')] $label ok"
  else
    echo "--- [$(date '+%H:%M:%S')] $label FAILED or timed out (status $?)"
  fi
}

for cycle in $(seq 1 24); do
  echo "=== [$(date '+%Y-%m-%d %H:%M:%S')] analysis cycle $cycle ==="
  records=$(cat "$RELEASE"/records/*.jsonl 2>/dev/null | wc -l | tr -d ' ')
  echo "    records on disk: $records"

  stage "splits"    "$SPLIT_TIMEOUT"    env PYTHONPATH=. "$PY" -u -m pharmacophore.splits    --release "$RELEASE"
  stage "baselines" "$BASELINE_TIMEOUT" env PYTHONPATH=. "$PY" -u -m pharmacophore.baselines --release "$RELEASE"
  stage "model"     "$TRAIN_TIMEOUT"    env PYTHONPATH=. "$PY" -u -m pharmacophore.train     --release "$RELEASE" --epochs "$EPOCHS"
  stage "figures"   "$FIGURE_TIMEOUT"   env PYTHONPATH=. "$PY" -u -m pharmacophore.figures   --release "$RELEASE"

  # Commit whatever this cycle produced. Splits, results and figures are the
  # tracked artefacts; the records stay out of git by design.
  git add "$RELEASE"/splits "$RELEASE"/results "$RELEASE"/figures 2>/dev/null
  if ! git diff --cached --quiet 2>/dev/null; then
    git commit -q -m "Analysis cycle $cycle: results at $records records

Generated by corpus/overnight.sh while the build continued.

Co-Authored-By: Claude Opus 5 <noreply@anthropic.com>" && echo "    committed"
  else
    echo "    nothing changed, no commit"
  fi

  echo "=== [$(date '+%H:%M:%S')] cycle $cycle done, sleeping ${CYCLE_SLEEP}s ==="
  sleep "$CYCLE_SLEEP"
done
