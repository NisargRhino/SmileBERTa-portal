#!/usr/bin/env bash
# The full analysis on the finished corpus, once, in order.
#
# Unlike overnight.sh this does not loop: the build is complete, so there is one
# corpus and one set of numbers to produce from it. Each stage has a hard
# timeout and a stage that overruns is killed rather than wedging the run --
# every later stage reads results from disk, so a failed stage costs its own
# output and nothing else.
set -u
cd "$(dirname "$0")/.."

RELEASE="${RELEASE:-corpus/v1}"
PY="${PY:-/private/tmp/claude-501/-Users-nisargshah-Documents-cs-SmileBERTa-portal/d5665c0f-0ea0-405a-b676-e25fb81ddc4d/scratchpad/tenv/bin/python}"
EPOCHS="${EPOCHS:-30}"

run_with_timeout() {
  local limit="$1"; shift
  "$@" &
  local pid=$!
  ( sleep "$limit"; kill -9 "$pid" 2>/dev/null ) &
  local killer=$!
  wait "$pid" 2>/dev/null
  local status=$?
  kill "$killer" 2>/dev/null
  return $status
}

stage() {
  local label="$1" limit="$2"; shift 2
  echo "=== [$(date '+%H:%M:%S')] $label"
  if run_with_timeout "$limit" "$@"; then
    echo "=== [$(date '+%H:%M:%S')] $label OK"
  else
    echo "=== [$(date '+%H:%M:%S')] $label FAILED (status $?)"
  fi
}

echo "### final run on $RELEASE, $(cat $RELEASE/records/*.jsonl | wc -l) records"

stage "splits"    3600  env PYTHONPATH=. "$PY" -u -m pharmacophore.splits          --release "$RELEASE"
stage "baselines" 10800 env PYTHONPATH=. "$PY" -u -m pharmacophore.baselines       --release "$RELEASE"
stage "model"     14400 env PYTHONPATH=. "$PY" -u -m pharmacophore.train           --release "$RELEASE" --epochs "$EPOCHS"
stage "geometric" 21600 env PYTHONPATH=. "$PY" -u -m pharmacophore.train_geometric --release "$RELEASE" --epochs "$EPOCHS"
stage "figures"   3600  env PYTHONPATH=. "$PY" -u -m pharmacophore.figures         --release "$RELEASE"

git add "$RELEASE"/splits "$RELEASE"/results "$RELEASE"/figures 2>/dev/null
if ! git diff --cached --quiet 2>/dev/null; then
  git commit -q -m "Final results on the complete corpus

Generated by corpus/final_run.sh after the build finished.

Co-Authored-By: Claude Opus 5 <noreply@anthropic.com>" && echo "### committed"
fi
echo "### [$(date '+%H:%M:%S')] final run done"
